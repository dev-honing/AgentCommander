/**
 * 실행(run) 단위 색.
 *
 * 상태 색(STATE_COLOR)과는 다른 축이다. 상태는 "이 에이전트가 지금 무엇을
 * 하는가", 실행 색은 "어느 질문에서 갈라져 나왔는가"를 답한다. 두 질문이
 * 섞이면 안 되므로 색조를 겹치지 않게 골랐다 — 상태가 회색·초록·노랑·주황·
 * 빨강·파랑을 쓰므로 여기서는 보라·청록·분홍 계열만 쓴다.
 */

// 상태 색이 회색·초록·노랑·주황·빨강·파랑을 차지하므로 남은 색조는
// 보라·청록·분홍뿐이다. 여섯 개를 다 다른 색조로 만들 수는 없어서
// 세 색조 × 밝기 두 단계로 나눴다.
//
// ⚠️ 비슷한 색조를 나란히 두면 안 된다. 처음에 청록(#14b8a6)과
//    하늘(#06b6d4)을 함께 썼다가 두 실행이 구분되지 않았다.
const RUN_COLORS = [
  '#c084fc', // 밝은 보라
  '#2dd4bf', // 밝은 청록
  '#f472b6', // 밝은 분홍
  '#7e22ce', // 진한 보라
  '#0f766e', // 진한 청록
  '#9d174d', // 진한 분홍
]

/** run_id 를 색으로 바꾼다. 같은 실행은 항상 같은 색이 된다. */
export function runColor(runId: string): string {
  let hash = 0
  for (let i = 0; i < runId.length; i++) {
    hash = (hash * 31 + runId.charCodeAt(i)) | 0
  }
  return RUN_COLORS[Math.abs(hash) % RUN_COLORS.length]
}
